/// Which glyph a character draws as. Lowercase folds to uppercase, and anything
/// outside the table becomes a space rather than an error -- text on screen
/// should degrade, not stop the frame.
pub fn glyphIndex(ch: u8) usize {
    const upper = if (ch >= 'a' and ch <= 'z') ch - 32 else ch;
    if (upper < first_char or upper >= end_char) return 0;
    return upper - first_char;
}

/// Expands the bit-packed glyphs into an RGBA atlas the uploader can take.
///
/// White everywhere, with the alpha carrying the glyph: the text shader tints
/// the colour itself, so one atlas serves every colour. The caller owns the
/// returned bytes.
pub fn buildAtlas(allocator: std.mem.Allocator) ![]u8 {
    const pixels = try allocator.alloc(u8, atlas_size * atlas_size * 4);
    errdefer allocator.free(pixels);
    @memset(pixels, 0);

    for (glyphs, 0..) |glyph, index| {
        const gx = (index % atlas_glyphs) * glyph_size;
        const gy = (index / atlas_glyphs) * glyph_size;
        for (glyph, 0..) |row, y| {
            for (0..glyph_size) |x| {
                // Bit 7 is the leftmost pixel.
                const lit = (row >> @intCast(7 - x)) & 1;
                if (lit == 0) continue;
                const px = gx + x;
                const py = gy + y;
                const o = (py * atlas_size + px) * 4;
                pixels[o + 0] = 255;
                pixels[o + 1] = 255;
                pixels[o + 2] = 255;
                pixels[o + 3] = 255;
            }
        }
    }
    return pixels;
}

test "every character in range maps to a glyph, and the rest to space" {
    try std.testing.expectEqual(@as(usize, 0), glyphIndex(' '));
    try std.testing.expectEqual(@as(usize, 'A' - 32), glyphIndex('A'));
    // Lowercase folds onto uppercase.
    try std.testing.expectEqual(glyphIndex('A'), glyphIndex('a'));
    try std.testing.expectEqual(glyphIndex('Z'), glyphIndex('z'));
    // Out of range degrades to a space rather than reading past the table.
    try std.testing.expectEqual(@as(usize, 0), glyphIndex(0));
    try std.testing.expectEqual(@as(usize, 0), glyphIndex(200));
}

test "the atlas is glyph-shaped and the letter A has lit pixels" {
    const a = std.testing.allocator;
    const pixels = try buildAtlas(a);
    defer a.free(pixels);

    try std.testing.expectEqual(@as(usize, atlas_size * atlas_size * 4), pixels.len);

    // 'A' has a lit pixel somewhere; a blank atlas would mean the bit unpacking
    // is wrong in a way no test of glyphIndex would catch.
    const index = glyphIndex('A');
    const gx = (index % atlas_glyphs) * glyph_size;
    const gy = (index / atlas_glyphs) * glyph_size;
    var lit: usize = 0;
    for (0..glyph_size) |y| {
        for (0..glyph_size) |x| {
            const o = ((gy + y) * atlas_size + (gx + x)) * 4;
            if (pixels[o + 3] != 0) lit += 1;
        }
    }
    try std.testing.expect(lit > 8);

    // Space is empty, which is what makes gaps between words gaps.
    var space_lit: usize = 0;
    for (0..glyph_size) |y| {
        for (0..glyph_size) |x| {
            const o = (y * atlas_size + x) * 4;
            if (pixels[o + 3] != 0) space_lit += 1;
        }
    }
    try std.testing.expectEqual(@as(usize, 0), space_lit);
}
