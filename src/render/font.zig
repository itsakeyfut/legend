//! An 8x8 bitmap font, and the atlas the text pipeline samples from.
//!
//! Sixty-four glyphs, ASCII 32 ('space') through 95 ('_'), laid out as an 8x8
//! grid of 8x8 pixels -- a 64x64 atlas whose coordinates are pure arithmetic.
//! Lowercase maps onto uppercase; a debug overlay does not need the distinction,
//! and the whole table stays under a kilobyte.
//!
//! The glyphs live in the binary rather than in a file: there is nothing to
//! load, nothing to fail, and no asset to keep alongside the executable. That
//! is exactly the tradeoff a debug overlay wants and a game's UI does not --
//! when real typography is called for, the source of glyphs changes here and
//! the pipeline that draws them does not.

const std = @import("std");

/// The first character the font covers. Anything below it draws as a space.
pub const first_char: u8 = 32;
/// One past the last character the font covers.
pub const end_char: u8 = 96;

/// Every glyph is this many pixels on a side.
pub const glyph_size: u32 = 8;
/// The atlas is a square grid of glyphs, so both dimensions are this.
pub const atlas_glyphs: u32 = 8;
/// The atlas in pixels: 8 glyphs across, 8 pixels each.
pub const atlas_size: u32 = glyph_size * atlas_glyphs;

